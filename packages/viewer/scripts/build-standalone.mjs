import { writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const __dirname = dirname(fileURLToPath(import.meta.url));
const pkgRoot = join(__dirname, "..");

const result = await build({
  entryPoints: [join(pkgRoot, "dist/standalone.js")],
  bundle: true,
  minify: true,
  format: "iife",
  platform: "browser",
  target: ["es2022"],
  write: false,
});

const bundledJs = result.outputFiles[0]?.text ?? "";
// Prevent premature </script> termination when embedded inside an HTML <script> tag
const safeJs = bundledJs.replace(/<\/script/gi, "<\\/script");

const { VIEWER_BASE_CSS } = await import(join(pkgRoot, "dist/styles/theme.js"));

const standaloneShellCss = `html,body{margin:0;padding:0;height:100%;overflow:hidden;display:flex;flex-direction:column}wa-message-list{flex:1;min-height:0}${VIEWER_BASE_CSS}`;

const jsModule = [
  "// Auto-generated by scripts/build-standalone.mjs — do not edit manually.",
  `export const STANDALONE_VIEWER_JS = ${JSON.stringify(safeJs)};`,
  `export const STANDALONE_VIEWER_CSS = ${JSON.stringify(standaloneShellCss)};`,
  "",
].join("\n");

const dtsModule = [
  "// Auto-generated by scripts/build-standalone.mjs — do not edit manually.",
  "export declare const STANDALONE_VIEWER_JS: string;",
  "export declare const STANDALONE_VIEWER_CSS: string;",
  "",
].join("\n");

await writeFile(join(pkgRoot, "dist/standalone-bundle.js"), jsModule, "utf8");
await writeFile(join(pkgRoot, "dist/standalone-bundle.d.ts"), dtsModule, "utf8");
